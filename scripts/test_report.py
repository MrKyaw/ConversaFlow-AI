"""Run the test suite and record measured line and branch coverage."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="conversaflow-tests-") as directory:
        coverage_path = Path(directory) / "coverage.json"
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                "--cov=src/conversaflow",
                "--cov-fail-under=80",
                f"--cov-report=json:{coverage_path}",
                "-q",
            ],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        print(result.stdout)
        if result.returncode != 0:
            print(result.stderr)
            return result.returncode
        coverage = json.loads(coverage_path.read_text())
    totals = coverage["totals"]
    lines = [
        "# Test results",
        "",
        "Generated by `python scripts/test_report.py` after a successful pytest run.",
        "The command fails on any failed test or combined coverage below 80%.",
        "",
        "## Test execution",
        "",
        "```text",
        result.stdout.strip().splitlines()[-1],
        "```",
        "",
        "## Coverage",
        "",
        f"- Statements: {totals['num_statements']}",
        f"- Covered lines: {totals['covered_lines']}",
        f"- Missing lines: {totals['missing_lines']}",
        f"- Line coverage: {100 * totals['covered_lines'] / totals['num_statements']:.2f}%",
        f"- Branches: {totals['num_branches']}",
        f"- Covered branches: {totals['covered_branches']}",
        f"- Combined line/branch coverage: {totals['percent_covered']:.2f}%",
        "",
        "Coverage is not a guarantee of correctness. Subprocess-only execution is not counted.",
        "",
        "## Per-module coverage",
        "",
        "| Module | Statements | Missing | Branches | Covered branches |",
        "|---|---:|---:|---:|---:|",
    ]
    for filename, data in sorted(coverage["files"].items()):
        summary = data["summary"]
        lines.append(
            f"| {filename} | {summary['num_statements']} | {summary['missing_lines']} | "
            f"{summary['num_branches']} | {summary['covered_branches']} |"
        )
    output = ROOT / "docs" / "TEST_RESULTS.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/TEST_RESULTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
